/** 이용약관·개인정보처리방침 창 (Esc·바깥 누르기로 닫힘, 열리면 초점이 창 안으로) */
export function LegalSheet({ kind, onClose }: { kind: LegalKind; onClose: () => void }) {
  return (
    <Sheet
      title={
        <>
          <Icon name={kind === 'privacy' ? 'lock' : 'book'} size={18} /> {kind === 'privacy' ? '개인정보처리방침' : '이용약관'}
        </>
      }
      onClose={onClose}
      wide
    >
      {kind === 'privacy' ? <PrivacyBody /> : <TermsBody />}
      <div className="modal-actions">
        <button className="btn primary" onClick={onClose}>
          확인
        </button>
      </div>
    </Sheet>
  );
}
