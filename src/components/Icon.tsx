export type IconName = keyof typeof ICONS;

export function Icon({ name, size = 16, className, label }: { name: IconName; size?: number; className?: string; label?: string }) {
  const C = ICONS[name];
  return <C size={size} strokeWidth={2} className={'ico' + (className ? ' ' + className : '')} aria-hidden={label ? undefined : true} aria-label={label} />;
}

